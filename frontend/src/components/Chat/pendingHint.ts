/**
 * 纯文本路径的「在等」提示。
 *
 * ## 为什么纯文本也需要提示
 *
 * 带图路径有 `pendingHint`（见 `MessageList` 的可选 prop），因为带图推理实测中位
 * 105.7s、最大 245.8s，三点动画干转四分钟用户会以为卡死。
 *
 * 纯文本此前没有提示，理由是「纯文本很快」。**这个理由只覆盖了短问答**：
 * `usage_ledger` 里 `tier=chat` 的 `tokens_out` 只有 5~107 的那几条恰好都是短问答；
 * dev-4 生产实测的纯文本长解释是 **66,078ms / tokens_out=4610** ——
 * 短问答几秒，长解释照样 60 秒+。所以纯文本同样会出现「干转一分钟以为卡了」。
 *
 * ## 为什么分两档
 *
 * **别一发送就弹提示**，那反而烦（绝大多数纯文本是秒级）。所以：
 *
 * - 第一档在 15 秒：绝大多数短问答已经结束，触发的都是异常慢的请求，
 *   这时给一句「在生成、可能要一会儿」是**必要信息**而不是打扰。
 * - 第二档在 45 秒：此时用户已经明显在等，升级文案，补一条**可执行**的信息
 *   （可以先去做别的），这是第一档没有的。
 *
 * 阈值取自实测：短问答秒级、长解释 66s。15s 卡在两者之间，45s 落在长解释的
 * 常见区间内 —— 两者都不是拍脑袋的数。
 *
 * ## 文案口径
 *
 * 守 `docs/visual-language.md` §6 文案红线：禁「请稍候」这种无信息量的说法，
 * 禁打鸡血词（冲刺/升级/你真棒/…），不外泄内部术语（画像/归因）。
 * 平平实实说清楚「在生成、可能要一会儿」。
 */

/** 第一档提示的触发时机（ms）。 */
export const TEXT_HINT_DELAY_MS = 15_000

/** 第二档（升级文案）的触发时机（ms）。 */
export const TEXT_HINT_SLOW_DELAY_MS = 45_000

/**
 * 第一档文案。
 *
 * 一句话两段：前半说状态（正在生成），后半给预期（可能要花些时间）。
 * 不用「请稍候」——那不提供任何信息。
 */
export const TEXT_HINT = '正在生成回答 · 这次可能要花些时间'

/**
 * 第二档文案。
 *
 * 比第一档多一条**可执行**的信息：可以先去做别的。措辞不评价用户、不评价回答质量，
 * 只陈述当前状态。
 */
export const TEXT_HINT_SLOW = '还在生成 · 可以先去做别的，回来再看'

/**
 * 启动纯文本路径的提示升级计时。
 *
 * 短问答不会触发任何一档（两次都在响应回来之后才到点），
 * 所以秒级问答的观感与从前**完全一致**。
 *
 * @param onHint 每次要升级文案时调用（第一档、第二档各一次）
 * @returns 取消函数：清掉两个定时器。**必须在请求结束/组件卸载时调用**，
 *   否则会在响应已到之后仍然弹出提示。
 */
export function startTextPendingHint(onHint: (hint: string) => void): () => void {
  const first = setTimeout(() => onHint(TEXT_HINT), TEXT_HINT_DELAY_MS)
  const second = setTimeout(() => onHint(TEXT_HINT_SLOW), TEXT_HINT_SLOW_DELAY_MS)
  return () => {
    clearTimeout(first)
    clearTimeout(second)
  }
}
